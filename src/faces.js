// darken / lighten a hex colour by a factor (posterised: whole steps only)
const shade = (hex, k) => {
  const n = parseInt(hex.slice(1), 16), f = (v) => Math.max(0, Math.min(255, Math.round(v * k)));
  return `#${((f(n >> 16 & 255) << 16) | (f(n >> 8 & 255) << 8) | f(n & 255)).toString(16).padStart(6, '0')}`;
};

const mix = (a, b, t) => { const p = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)), A = p(a), B = p(b); return `#${A.map((v, i) => Math.round(v + (B[i] - v) * t).toString(16).padStart(2, '0')).join('')}`; };

/** the colour of every legend letter for a speaker (sp: H hair, S skin, C clothes, A accent; optional beard, eyes, mouth) */
function palette(sp) {
  const dark = !!sp.eyes;   // "someone": no skin, no whites, only the pale eyes
  return {
    o: dark ? '#0a0810' : '#1a0f08',
    S: sp.S, s: shade(sp.S, 0.78), L: shade(sp.S, 1.12), R: mix(sp.S, '#d0503a', 0.35),
    W: dark ? sp.eyes : '#f4ead0', E: '#1a0f08', B: shade(sp.H === '#e8e0d0' ? '#a8a090' : sp.H, 0.7),
    H: sp.H, h: shade(sp.H, 0.72), G: shade(sp.H, 1.35),
    X: sp.beard || shade(sp.H, 0.95), x: shade(sp.beard || sp.H, 0.72),
    M: sp.mouth || '#7a3a2a', T: '#f4ead0',
    C: sp.C, c: shade(sp.C, 0.72), A: sp.A, P: '#6b4a2e', F: '#ffd060',
    ...(sp.pal || {}),   // per-speaker colour overrides (the diver's glass and cracks)
  };
}

/** draw a speaker's portrait on a fresh 16x16 canvas */
export function drawFace(id, sp) {
  const rows = T[id] || T.fisher, col = palette(sp);
  const cv = document.createElement('canvas'); cv.width = cv.height = 16;
  const c = cv.getContext('2d');
  rows.forEach((row, y) => [...row].forEach((ch, x) => { const v = col[ch]; if (v) { c.fillStyle = v; c.fillRect(x, y, 1, 1); } }));
  return cv;
}
